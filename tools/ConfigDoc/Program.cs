// Generates the parameter reference of docs/CONFIG.md from the code itself:
// defaults (instantiating ModConfig), real clamp ranges (probing Normalize with extreme values) and
// descriptions (XML documentation of CompetentAI.Core). Usage: dotnet run --project tools/ConfigDoc -- <output.md>
using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Xml.Linq;
using CompetentAI.Core;
using Newtonsoft.Json.Linq;

internal static class Program
{
    private static Dictionary<string, string> _docs = new Dictionary<string, string>();

    private static int Main(string[] args)
    {
        if (args.Length >= 3 && args[0] == "weapons") return Weapons(args[1], args[2]);
        string xmlPath = Path.ChangeExtension(typeof(ModConfig).Assembly.Location, ".xml");
        if (File.Exists(xmlPath))
            foreach (XElement m in XDocument.Load(xmlPath).Descendants("member"))
            {
                string name = (string)m.Attribute("name");
                string sum = (string)m.Element("summary");
                if (name != null && sum != null) _docs[name] = Clean(sum);
            }

        var sb = new StringBuilder();
        sb.AppendLine("<!-- GENERATED by tools/ConfigDoc from the code. Do not edit by hand; rerun the tool. -->");
        sb.AppendLine();
        var cfg = new ModConfig();
        cfg.Normalize();

        Section(sb, "Modules", typeof(ModulesConfig), cfg.Modules, "Modules", cfg);
        Section(sb, "Assignment", typeof(AssignmentConfig), cfg.Assignment, "Assignment", cfg);
        Section(sb, "Rules", typeof(RulesConfig), cfg.Rules, "Rules", cfg);
        Section(sb, "Variety", typeof(VarietyConfig), cfg.Variety, "Variety", cfg);
        Section(sb, "Feints", typeof(FeintConfig), cfg.Feints, "Feints", cfg);
        Section(sb, "Defense", typeof(DefenseConfig), cfg.Defense, "Defense", cfg);
        Section(sb, "Calibration", typeof(CalibrationConfig), cfg.Calibration, "Calibration", cfg);
        Section(sb, "Logging", typeof(LoggingConfig), cfg.Logging, "Logging", cfg);

        sb.AppendLine("## Profiles (archetypes)");
        sb.AppendLine();
        sb.AppendLine("Each profile has the same fields. Defaults per archetype:");
        sb.AppendLine();
        var profiles = SkillProfile.CreateDefaults();
        string[] order = { "Recruit", "Soldier", "Veteran", "Duelist" };
        sb.AppendLine("| Field | Meaning | Range | " + string.Join(" | ", order) + " |");
        sb.AppendLine("|---|---|---|" + string.Join("|", order.Select(_ => "---")) + "|");
        foreach (FieldInfo f in typeof(SkillProfile).GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            string doc = Doc(f);
            string range = Range(() => new SkillProfile(), f, o => ((SkillProfile)o).Clamp());
            sb.AppendLine($"| `{f.Name}` | {doc} | {range} | " + string.Join(" | ", order.Select(n => Fmt(f.GetValue(profiles[n])))) + " |");
        }
        sb.AppendLine();

        File.WriteAllText(args.Length > 0 ? args[0] : "config-reference.md", sb.ToString());
        return 0;
    }

    private static void Section(StringBuilder sb, string title, Type type, object instance, string jsonKey, ModConfig cfg)
    {
        sb.AppendLine("## " + title);
        sb.AppendLine();
        sb.AppendLine("| Key | Default | Range | Description |");
        sb.AppendLine("|---|---|---|---|");
        foreach (FieldInfo f in type.GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            string range = Range(() => { var c = new ModConfig(); c.Normalize(); return c; }, f, null, instance, jsonKey);
            sb.AppendLine($"| `{jsonKey}.{f.Name}` | {Fmt(f.GetValue(instance))} | {range} | {Doc(f)} |");
        }
        sb.AppendLine();
    }

    private static string Doc(FieldInfo f)
    {
        _docs.TryGetValue("F:" + f.DeclaringType.FullName + "." + f.Name, out string d);
        return d ?? "";
    }

    private static string Clean(string s) => string.Join(" ", s.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries).Select(x => x.Trim())).Replace("|", "/");

    private static string Fmt(object v)
    {
        if (v == null) return "null";
        if (v is bool b) return b ? "true" : "false";
        if (v is float fl) return fl.ToString("0.###", CultureInfo.InvariantCulture);
        if (v is double db) return db.ToString("0.###", CultureInfo.InvariantCulture);
        if (v is Enum) return v.ToString();
        if (v is IDictionary d) return d.Count == 0 ? "{}" : "{" + string.Join(", ", d.Keys.Cast<object>().Take(6).Select(k => k + "=" + (d[k] is string s ? s : "…"))) + (d.Count > 6 ? ", …" : "") + "}";
        if (v is IList l) return "[" + string.Join(", ", l.Cast<object>()) + "]";
        return v.ToString();
    }

    // Probes the real clamp range of a numeric field by feeding it extreme values through Normalize()/Clamp().
    private static string Range(Func<object> make, FieldInfo f, Action<object> clamp, object unused = null, string jsonKey = null)
    {
        Type t = f.FieldType;
        if (t == typeof(bool)) return "true/false";
        if (t != typeof(float) && t != typeof(int)) return "";
        double lo = Probe(make, f, clamp, jsonKey, -1e9), hi = Probe(make, f, clamp, jsonKey, 1e9);
        if (Math.Abs(lo) > 1e8 && Math.Abs(hi) > 1e8) return "any";
        if (Math.Abs(lo) > 1e8) return "≤ " + hi.ToString("0.###", CultureInfo.InvariantCulture);
        if (Math.Abs(hi) > 1e8) return "≥ " + lo.ToString("0.###", CultureInfo.InvariantCulture);
        return lo.ToString("0.###", CultureInfo.InvariantCulture) + " … " + hi.ToString("0.###", CultureInfo.InvariantCulture);
    }

    private static double Probe(Func<object> make, FieldInfo f, Action<object> clamp, string jsonKey, double value)
    {
        object root = make();
        object target = root;
        if (jsonKey != null)
            target = typeof(ModConfig).GetField(jsonKey).GetValue(root);
        object boxed = f.FieldType == typeof(int) ? (object)(int)Math.Max(int.MinValue, Math.Min(int.MaxValue, value)) : (float)value;
        f.SetValue(target, boxed);
        if (clamp != null) clamp(target); else ((ModConfig)root).Normalize();
        return Convert.ToDouble(f.GetValue(target), CultureInfo.InvariantCulture);
    }

    // Applies the weapon rules to every melee item of the base game (items dir = extracted bas.jsondb/Items).
    private static int Weapons(string itemsDir, string output)
    {
        var rules = new AttackRules(new RulesConfig());
        var rows = new List<string[]>();
        foreach (string file in Directory.GetFiles(itemsDir, "*.json"))
        {
            JObject o;
            try { o = JObject.Parse(File.ReadAllText(file)); } catch { continue; }
            JToken ai = (o["modules"] as JArray)?.FirstOrDefault(m => ((string)m["$type"] ?? "").Contains("ItemModuleAI"));
            if (ai == null) continue;
            string primary = (string)ai["primaryClass"], secondary = (string)ai["secondaryClass"];
            if (primary != "Melee" && primary != "Shield" && secondary != "Melee") continue;
            string id = (string)o["id"];
            var ids = (o["damagers"] as JArray)?.Select(d => (string)d["damagerID"]).ToList() ?? new List<string>();
            DamageTraits traits = WeaponClassifier.TraitsFromDamagerIds(ids);
            bool two = (string)ai["weaponHandling"] == "TwoHanded";
            string kindsText = (string)ai["weaponAttackTypes"] ?? "";
            AttackKinds kinds = (kindsText.Contains("Swing") ? AttackKinds.Swing : 0) | (kindsText.Contains("Thrust") ? AttackKinds.Thrust : 0);
            WeaponClass cls = WeaponClassifier.Classify(id, traits, two, primary == "Shield");
            var w = new WeaponProfile { ItemId = id, Traits = traits, DataKinds = kinds, TwoHanded = two, Class = cls, InfoKnown = traits != DamageTraits.None };
            bool swing = rules.Evaluate(w, null, new AttackCandidate { Id = "Swing", Kind = AttackKind.Swing }).Allowed;
            bool thrust = rules.Evaluate(w, null, new AttackCandidate { Id = "Thrust", Kind = AttackKind.Thrust }).Allowed;
            bool swingFinal = swing && (kinds & AttackKinds.Swing) != 0;
            bool thrustFinal = thrust && (kinds & AttackKinds.Thrust) != 0;
            bool stockSwing = (kinds & AttackKinds.Swing) != 0, stockThrust = (kinds & AttackKinds.Thrust) != 0;
            string change = (stockSwing && !swingFinal ? "pierde cortes " : "") + (stockThrust && !thrustFinal ? "pierde estocadas" : "");
            rows.Add(new[] { id, cls.ToString(), traits.ToString().Replace(", ", "+"), two ? "2H" : "1H", kinds.ToString().Replace(", ", "+"),
                             swingFinal ? "sí" : "no", thrustFinal ? "sí" : "no", change.Trim() });
        }
        var sb = new StringBuilder();
        sb.AppendLine("<!-- GENERATED by tools/ConfigDoc weapons: reglas de ataque aplicadas a los items cuerpo a cuerpo del juego base 1.3.1 -->");
        sb.AppendLine();
        sb.AppendLine("| Item | Clase | Rasgos (daño real) | Manos | Flags del item | Cortes | Estocadas | Cambio frente al juego de serie |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|");
        foreach (var r in rows.OrderBy(r => r[1]).ThenBy(r => r[0])) sb.AppendLine("| " + string.Join(" | ", r) + " |");
        File.WriteAllText(output, sb.ToString());
        Console.WriteLine(rows.Count + " weapons");
        return 0;
    }
}
