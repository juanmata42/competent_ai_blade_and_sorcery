#!/usr/bin/env python3
"""Generates the catalog content of the "Sparring" spells: the loadout containers and the two spell definitions.

Only IDs of existing game items are referenced (no game data is copied). Output goes to mod/CompetentAI/{Containers,Spells}.
Run:  python tools/gen-sparring-content.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "mod", "CompetentAI")

# Plain civilian clothes (ids taken from the game's own "CivilianMeleeSword" container).
APPAREL = ["ApparelCivilianHandL", "ApparelCivilianHandR", "ApparelCivilianChest", "ApparelCivilianLegs", "ApparelCivilianBoots"]

# name -> list of (itemId, holder). Holders as used by the game's own containers: BackRight / BackLeft.
LOADOUTS = {
    "Sword": [("SwordLongCommon", "BackRight")],
    "Dagger": [("DaggerCommon", "BackRight")],
    "Stiletto": [("DaggerSentaraStiletto", "BackRight")],
    "Rapier": [("Rapier", "BackRight")],
    "Spear": [("SpearBladed", "BackRight")],
    "Halberd": [("AxeLongHalberd", "BackRight")],
    "Axe": [("AxeShortCommon", "BackRight")],
    "Mace": [("MaceShortCommon", "BackRight")],
    "Maul": [("MaceLongMaul", "BackRight")],
    "Greatsword": [("SwordGreatCommon", "BackRight")],
    "Staff": [("DualBladeStaff", "BackRight")],
    "SwordShield": [("SwordLongCommon", "BackRight"), ("ShieldRound", "BackLeft")],
    "DualWield": [("SwordShortCommon", "BackRight"), ("SwordShortCommon", "BackLeft")],
    "Dummy": [("SwordLongCommon", "BackRight"), ("ShieldRound", "BackLeft")],
}


def merge_key(text):
    h = 2166136261
    for ch in text:
        h = ((h ^ ord(ch)) * 16777619) & 0xFFFFFFFF
    return "%08x" % h


def item_content(item_id, state, key):
    return {
        "$type": "ThunderRoad.ItemContent, ThunderRoad",
        "quantity": 1,
        "state": state,
        "customDataList": [],
        "mergeKey": merge_key(key),
        "referenceID": item_id,
    }


def container(name, weapons):
    cid = "CompetentSpar_" + name
    contents = []
    for i, (item, holder) in enumerate(weapons):
        contents.append(item_content(item, {"$type": "ThunderRoad.ContentStateHolder, ThunderRoad", "holderName": holder}, "%s-w%d-%s" % (cid, i, item)))
    for item in APPAREL:
        contents.append(item_content(item, {"$type": "ThunderRoad.ContentStateWorn, ThunderRoad"}, "%s-a-%s" % (cid, item)))
    return cid, {
        "$type": "ThunderRoad.ContainerData, ThunderRoad",
        "id": cid,
        "sensitiveContent": "None",
        "sensitiveFilterBehaviour": "Discard",
        "version": 1,
        "groupPath": "CompetentAI/Sparring",
        "displayName": "Competent AI sparring: " + name,
        "description": "Practice NPC loadout (generated by tools/gen-sparring-content.py)",
        "containerContents": contents,
    }


def spell(spell_id, mode, wheel_name, order, icon):
    return {
        "$type": "CompetentAI.Mod.SpellSparring, CompetentAI",
        "id": spell_id,
        "sensitiveContent": "None",
        "sensitiveFilterBehaviour": "Discard",
        "version": 0,
        "groupPath": "CompetentAI",
        "mode": mode,
        "wheelDisplayName": wheel_name,
        "hasOrder": True,
        "order": order,
        "iconEffectId": icon,
        "aiCastType": "CastSimple",
        # Default skills are added to the player's spell wheel automatically (Creature.LoadDefaultSkills).
        "allowSkill": True,
        "isDefaultSkill": True,
        "showInTree": False,
        "hideInSkillMenu": True,
        "tier": 0,
        "primarySkillTreeId": "",
        "secondarySkillTreeId": "",
        "description": "Summons practice NPCs (Competent AI).",
    }


def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


def main():
    for name, weapons in LOADOUTS.items():
        cid, data = container(name, weapons)
        write(os.path.join(OUT, "Containers", "Container_%s.json" % cid), data)
    write(os.path.join(OUT, "Spells", "Spell_CompetentSparAttackers.json"),
          spell("CompetentSparAttackers", "Attackers", "Spar: weapons", 90, "SpellOrbLightning"))
    write(os.path.join(OUT, "Spells", "Spell_CompetentSparDummy.json"),
          spell("CompetentSparDummy", "Dummy", "Spar: parry dummy", 91, "SpellOrbFire"))
    print("generated %d containers and 2 spells in %s" % (len(LOADOUTS), OUT))


if __name__ == "__main__":
    main()
